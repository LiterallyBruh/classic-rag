"""Структурные (позиционные) вопросы: «чем заканчивается», «последняя фраза».

Similarity-поиск на такие вопросы принципиально не отвечает: слово
«последняя» описывает позицию в книге, а не содержание чанка — финал
романа ничем не «похож» на такой запрос ни лексически, ни семантически
(D-011). Поэтому позиционный интент распознаётся правилами, и кандидаты
берутся срезом из головы/хвоста книги в порядке повествования, а уже
среди них реранкер выбирает релевантные (например, упоминающие персонажа).

Правила осознанно консервативные: ложное срабатывание подменяет весь
поиск срезом книги, поэтому «в начале/в конце» учитываются только
применительно к произведению целиком.
"""

from __future__ import annotations

import re

# «последний разговор/встреча» — контентные вопросы (сцена может быть где
# угодно), поэтому «последн…» триггерит только с единицами текста
_TAIL = re.compile(
    r"\bпоследн\w+\s+(?:фраз|слов|реплик|предложени|сцен|глав|абзац|строк)\w*"
    r"|\bфинал\w*"
    r"|\bконцовк\w*"
    r"|\bразвязк\w*"
    r"|\bчем\s+(?:за)?канчива\w*"
    r"|\bв\s+(?:самом\s+)?конце\s+(?:роман|книг|произведени|поэм|трагеди)\w*",
    re.IGNORECASE,
)
_HEAD = re.compile(
    r"\bперв\w+\s+(?:фраз|слов|предложени|сцен|глав|строк|абзац)\w*"
    r"|\bс\s+чего\s+начина\w*"
    r"|\bв\s+(?:самом\s+)?начале\s+(?:роман|книг|произведени|поэм|трагеди)\w*",
    re.IGNORECASE,
)

# Упоминание книги в самом вопросе — для режима «все книги» в демо.
_BOOK_MARKERS = {
    "prestuplenie_i_nakazanie": ("преступлен",),
    "idiot": ("идиот",),
    "besy": ("бесы", "бесах", "бесов", "бесам"),
    "faust_holodkovsky": ("фауст",),
}


def positional_intent(query: str) -> str | None:
    """'head' | 'tail' | None. При конфликте побеждает tail: «последняя» —
    сильный маркер, а «первый» часто встречается в обычных вопросах."""
    if _TAIL.search(query):
        return "tail"
    if _HEAD.search(query):
        return "head"
    return None


def resolve_book(query: str) -> str | None:
    """Книга, названная в вопросе; None, если не названа или названо несколько."""
    q = query.lower()
    hits = [book for book, markers in _BOOK_MARKERS.items() if any(m in q for m in markers)]
    return hits[0] if len(hits) == 1 else None
